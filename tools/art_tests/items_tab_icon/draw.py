# Open wooden chest tab icon, 16x16. Palette = hammer tab icon outline + wood, plus wood ramp/brass from DESIGN palette.
from PIL import Image
PAL={'O':(30,30,38),'b':(122,75,39),'c':(150,102,60),'d':(205,145,90),'a':(71,40,13),
     'q':(198,138,53),'r':(240,186,98),'i':(44,28,22),'.':None}
ART="""
................
..bbbbbbbbbb....
.bddddddddddc...
.bccccccccccc...
.bcaaaaaaaaac...
.bbbaaaaaaabb...
..bcqrqiiqrqc...
.bddddddddddc...
.bccccccccccc...
.bcccccqqcccc...
.bcccccqqcccc...
.bccccccccccc...
.bbbbbbbbbbbb...
................
................
................"""
rows=ART.strip("\n").split("\n")
assert len(rows)==16 and all(len(r)==16 for r in rows),[len(r) for r in rows]
def build():
    im=Image.new("RGBA",(16,16),(0,0,0,0))
    for y,r in enumerate(rows):
        for x,ch in enumerate(r):
            if PAL[ch]: im.putpixel((x,y),PAL[ch]+(255,))
    o=im.copy()   # 1 px outline all round, like the hammer
    for y in range(16):
        for x in range(16):
            if im.getpixel((x,y))[3]==0 and any(0<=x+dx<16 and 0<=y+dy<16 and im.getpixel((x+dx,y+dy))[3] for dx,dy in((1,0),(-1,0),(0,1),(0,-1))):
                o.putpixel((x,y),PAL['O']+(255,))
    return o
if __name__=="__main__":
    im=build(); im.save("assets/game/ui/skin/items_tab_icon.png")
    S=10; names=["assets/game/ui/placeholder/hammer.png","assets/game/ui/skin/items_tab_icon.png"]
    sheet=Image.new("RGBA",(16*S*len(names)+S*(len(names)+1),16*S+2*S),(90,110,90,255))
    for i,n in enumerate(names):
        t=Image.open(n).convert("RGBA").resize((16*S,16*S),Image.NEAREST)
        sheet.alpha_composite(t,(S+i*(16*S+S),S))
    sheet.save("tools/art_tests/items_tab_icon/zoom.png")
