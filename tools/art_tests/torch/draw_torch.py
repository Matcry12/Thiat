def img(rows):
    w=len(rows[0]); assert all(len(r)==w for r in rows),[len(r) for r in rows]
    im=Image.new('RGBA',(w,len(rows)))
    for y,r in enumerate(rows):
        for x,c in enumerate(r):
            if c!='.': im.putpixel((x,y),PAL[c]+(255,))
    return im
def frame(i):
    f=FL[i].strip('\n').split('\n'); rows=[r for r in BASE]
    # flame occupies rows 3..8 over the wrap top (rows 9+)
    rows[3:9]=f
    return rows
