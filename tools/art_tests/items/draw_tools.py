ITEMS = {'sword': SWORD, 'pickaxe': PICKAXE, 'axe': AXE, 'shovel': SHOVEL, 'hammer': HAMMER}


def render(art, tier):
    rows = art.strip('\n').split('\n')
    w = 16
    for i, r in enumerate(rows):
        assert len(r) <= w, f'row {i} too wide ({len(r)}): {r}'
    im = Image.new('RGBA', (w, len(rows)), (0, 0, 0, 0))
    pal = dict(PAL)
    for i, col in enumerate(TIERS[tier]):
        pal[str(i + 1)] = col
    for y, r in enumerate(rows):
        for x, ch in enumerate(r):
            if ch != '.':
                im.putpixel((x, y), pal[ch] + (255,))
    return im


if __name__ == '__main__':
    out = sys.argv[1] if len(sys.argv) > 1 else '.'
    k, cell_h = 8, 48
    sheet = Image.new('RGBA', (len(ITEMS) * 16 * k + 40, len(TIERS) * cell_h * k), (90, 110, 90, 255))
    for ty, tier in enumerate(TIERS):
        for ix, (name, art) in enumerate(ITEMS.items()):
            im = render(art, tier)
            im.save(f'{out}/{tier}_{name}.png')
            big = im.resize((im.width * k, im.height * k), Image.NEAREST)
            sheet.alpha_composite(big, (ix * (16 * k + 10), ty * cell_h * k + (cell_h - im.height) * k))
    sheet.save(f'{out}/sheet_zoom.png')
