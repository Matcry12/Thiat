if __name__ == '__main__':
    out = sys.argv[1] if len(sys.argv) > 1 else '.'
    k = 10
    sheet = Image.new('RGBA', (len(ICONS) * 18 * k, len(TIERS) * 18 * k), (90, 110, 90, 255))
    for ty, tier in enumerate(TIERS):
        for ix, (name, art) in enumerate(ICONS.items()):
            im = render(art, tier)
            assert im.size == (16, 16), (name, im.size)
            im.save(f'{out}/{name}.png' if tier == 'iron' else f'{out}/{tier}_{name}.png')
            sheet.alpha_composite(im.resize((16 * k, 16 * k), Image.NEAREST), (ix * 18 * k + k, ty * 18 * k + k))
    sheet.save(f'{out}/icons_zoom.png')
